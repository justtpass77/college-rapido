import type { Ride } from "../types";

// Helper to build ISO date strings relative to "today" so the demo always
// shows fresh-looking upcoming rides no matter when it is run.
const isoDate = (daysFromToday: number) => {
  const d = new Date();
  d.setDate(d.getDate() + daysFromToday);
  return d.toISOString().slice(0, 10);
};

const yesterday = (daysAgo: number) => isoDate(-daysAgo);

